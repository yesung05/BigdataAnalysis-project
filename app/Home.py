import sys
from pathlib import Path

import streamlit as st

_PROJ_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_PROJ_DIR))

st.set_page_config(
    page_title="서울 구급·응급 인프라 분석",
    page_icon="🚑",
    layout="wide",
)

# ── 타이틀 ────────────────────────────────────────────────────────────────
st.title("🚑 서울 구급·응급 인프라 실태 분석")
st.caption("소방청 구급출동현황 2017–2022 · 서울시 출동현황 2022–2024 · 서울시 응급실 위치 정보")

st.divider()

# ── 문제 제기 ──────────────────────────────────────────────────────────────
st.subheader("📌 왜 이 분석인가")
st.markdown("""
서울에서는 하루 평균 **약 1,700건**의 구급 출동이 발생합니다.
2017년 약 54만 건이던 연간 출동 건수는 2022년 약 62만 건으로 **6년간 15% 증가**했습니다.

이 가운데 일부 환자는 첫 병원에서 수용을 거부당해 두 번째, 세 번째 병원을 찾아 헤매야 합니다.
이른바 **"뺑뺑이"(2차 이송)** 문제입니다.

2차 이송은 단순 불편이 아닙니다. **골든타임을 직접 침해**하며, 심정지·뇌졸중 환자에게는 생존율 저하로 이어집니다.
본 분석은 구급 출동 데이터를 통해 뺑뺑이가 **어디서·왜 발생하는지**, 그리고 응급 의료 인프라와 어떤 관계가 있는지를 파악합니다.
""")

st.divider()

# ── 분석 흐름 ──────────────────────────────────────────────────────────────
st.subheader("🗺 분석 흐름")

cols = st.columns(7)
steps = [
    ("1", "데이터\n현황",     "어떤 데이터를\n사용했나",          "📊"),
    ("2", "출동\n트렌드",    "수요가 얼마나\n늘었나",            "📈"),
    ("3", "뺑뺑이\n분석",    "어디서·왜\n발생하는가",            "🚨"),
    ("4", "응급실\n상관",    "응급실 접근성과\n뺑뺑이의 관계",   "🏥"),
    ("5", "소방서\n현황",    "인프라는\n어디에 집중됐나",        "🔥"),
    ("6", "증상\n분석",      "어떤 환자가\n어떤 결과를 맞나",    "💊"),
    ("7", "날씨\n상관",      "기온이 오르면\n출동이 늘어나나",   "🌡️"),
]
for col, (num, title, desc, icon) in zip(cols, steps):
    col.markdown(
        f"""<div style="text-align:center; padding:10px; border:1px solid #ddd;
        border-radius:8px; background:#f8f9fa; min-height:130px">
        <div style="font-size:1.4em">{icon}</div>
        <div style="font-weight:700; font-size:0.9em; margin:4px 0">
        {num}. {title.replace(chr(10), '<br>')}</div>
        <div style="font-size:0.78em; color:#666">{desc.replace(chr(10), '<br>')}</div>
        </div>""",
        unsafe_allow_html=True,
    )

st.divider()

# ── 주요 발견 ──────────────────────────────────────────────────────────────
st.subheader("🔍 주요 발견 요약")

col1, col2 = st.columns(2)

with col1:
    st.markdown("**구급 수요 & 뺑뺑이**")
    st.info("""
- 2022년 **62만 건** — 6개년 최고치 (2020년 코로나 감소 후 반등)
- 서울 2차 이송 발생률 **최대 0.42%** (서대문구) vs **최소 0.04%** (강동구) — 자치구 간 **10배 격차**
- 뺑뺑이 원인 1위 **'진료 불가'(72건)**, 2위 '응급실 포화(65건)' — 야간 전문의 부재가 핵심
- 2차 이송 시 추가 이동 거리 **중앙값 2.0 km, 평균 3.4 km** (최대 25 km)
""")

with col2:
    st.markdown("**인프라 & 환경 요인**")
    st.info("""
- 역삼119안전센터 **2,055건**으로 서울 1위 — 하위 센터(970건) 대비 **2.1배** 과부하
- 서울 응급실 76개소 중 **종합병원(A) 62개** — 자치구별 분포 불균형
- 기온이 유일한 유의미 날씨 변수 **(r=0.267, p=0.012)** — 더울수록 출동 증가
- 질병외(사고·외상) **50.3%** vs 질병 **47.1%** — 거의 동등한 비율
""")

st.divider()

